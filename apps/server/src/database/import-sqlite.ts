// SQLite is only an offline input format here, never the new runtime backend.
import { DatabaseSync } from 'node:sqlite';
import type { SQLInputValue } from 'node:sqlite';
import { lstat } from 'node:fs/promises';
import type { Postgres } from './postgres.js';
import { fileHashAsync } from '../library/files.js';

interface Column {
  name: string;
  type: string;
  notnull: number;
  dflt_value: string | null;
  pk: number;
}
interface Table {
  name: string;
  sql: string;
}
export interface ImportProgress {
  table: string;
  rows: number;
  completed: boolean;
}
const identifier = (value: string): string => {
  if (!/^[a-z][a-z0-9_]{0,62}$/.test(value)) throw Error('INVALID_MIGRATION_IDENTIFIER');
  return `"${value}"`;
};
const columnType = (value: string): string => {
  switch (value.toUpperCase()) {
    case 'INTEGER':
      return 'BIGINT';
    case 'REAL':
      return 'DOUBLE PRECISION';
    case 'TEXT':
      return 'TEXT';
    case 'BLOB':
      return 'BYTEA';
    default:
      throw Error('UNSUPPORTED_MIGRATION_COLUMN');
  }
};
const defaultValue = (value: string | null): string => {
  if (value === null) return '';
  if (!/^(?:-?[0-9]+(?:\.[0-9]+)?|NULL|'(?:[^']|'')*')$/i.test(value))
    throw Error('UNSUPPORTED_MIGRATION_DEFAULT');
  return ` DEFAULT ${value}`;
};
/** Resumable, bounded transfer into an isolated schema from an immutable SQLite backup. */
export async function importSqlite(options: {
  db: Postgres;
  source: string;
  schema: string;
  progress?: (progress: ImportProgress) => void;
}): Promise<{ tables: number; rows: number; sourceHash: string }> {
  const schema = identifier(options.schema);
  const source = await lstat(options.source);
  if (!source.isFile() || source.isSymbolicLink()) throw Error('UNSAFE_MIGRATION_SOURCE');
  for (const suffix of ['-wal', '-journal']) {
    try {
      const sidecar = await lstat(options.source + suffix);
      if (sidecar.size) throw Error('SQLITE_MIGRATION_REQUIRES_FROZEN_SNAPSHOT');
    } catch (error) {
      if (!(error instanceof Error && 'code' in error && error.code === 'ENOENT')) throw error;
    }
  }
  const sourceHash = await fileHashAsync(options.source);
  const input = new DatabaseSync(options.source, { readOnly: true });
  try {
    input.exec('BEGIN');
    const tables = input
      .prepare(
        "SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name",
      )
      .all() as unknown as Table[];
    const [existing] = await options.db.query<{ present: boolean; owned: boolean }>(
      `SELECT EXISTS(SELECT 1 FROM pg_namespace WHERE nspname=$1) AS present,
       to_regclass($2) IS NOT NULL AS owned`,
      [options.schema, `${options.schema}._import_source`],
    );
    if (existing.present && !existing.owned) throw Error('MIGRATION_TARGET_NOT_OWNED');
    await options.db.query(`CREATE SCHEMA IF NOT EXISTS ${schema}`);
    await options.db.query(
      `CREATE TABLE IF NOT EXISTS ${schema}._import_source(id SMALLINT PRIMARY KEY CHECK(id=1),hash TEXT NOT NULL)`,
    );
    await options.db.query(
      `INSERT INTO ${schema}._import_source VALUES(1,$1) ON CONFLICT(id) DO NOTHING`,
      [sourceHash],
    );
    const [owner] = await options.db.query<{ hash: string }>(
      `SELECT hash FROM ${schema}._import_source WHERE id=1`,
    );
    if (owner.hash !== sourceHash) throw Error('MIGRATION_SOURCE_CHANGED');
    await options.db.query(`CREATE TABLE IF NOT EXISTS ${schema}._import_state(
      name TEXT PRIMARY KEY,source_hash TEXT NOT NULL,cursor BIGINT,
      rows BIGINT NOT NULL DEFAULT 0,completed BOOLEAN NOT NULL DEFAULT false)`);
    let total = 0;
    for (const table of tables) {
      const name = identifier(table.name),
        qualified = `${schema}.${name}`;
      const columns = input.prepare(`PRAGMA table_info(${name})`).all() as unknown as Column[];
      if (!columns.length || columns.some((column) => column.name === '__migration_rowid'))
        throw Error('UNSUPPORTED_MIGRATION_TABLE');
      const primary = columns
        .filter((column) => column.pk)
        .sort((a, b) => a.pk - b.pk)
        .map((column) => identifier(column.name));
      if (!primary.length || /WITHOUT\s+ROWID/i.test(table.sql))
        throw Error('UNSUPPORTED_MIGRATION_TABLE');
      const identity = /\bAUTOINCREMENT\b/i.test(table.sql);
      await options.db.query(
        `CREATE TABLE IF NOT EXISTS ${qualified}(${columns
          .map(
            (column) =>
              `${identifier(column.name)} ${columnType(column.type)}${identity && column.pk ? ' GENERATED BY DEFAULT AS IDENTITY' : ''}${column.notnull ? ' NOT NULL' : ''}${defaultValue(column.dflt_value)}`,
          )
          .join(',')},PRIMARY KEY(${primary.join(',')}))`,
      );
      await options.db.query(
        `INSERT INTO ${schema}._import_state(name,source_hash) VALUES($1,$2) ON CONFLICT(name) DO NOTHING`,
        [table.name, sourceHash],
      );
      const [state] = await options.db.query<{
        source_hash: string;
        cursor: number | null;
        rows: number;
        completed: boolean;
      }>(`SELECT source_hash,cursor,rows,completed FROM ${schema}._import_state WHERE name=$1`, [
        table.name,
      ]);
      if (state.source_hash !== sourceHash) throw Error('MIGRATION_SOURCE_CHANGED');
      let cursor = state.cursor,
        rows = state.rows;
      if (!state.completed) {
        for (;;) {
          const iterator = input
            .prepare(
              `SELECT rowid AS __migration_rowid,${columns.map((column) => identifier(column.name)).join(',')} FROM ${name} ${cursor === null ? '' : 'WHERE rowid>?'} ORDER BY rowid LIMIT 128`,
            )
            .iterate(...(cursor === null ? [] : [cursor]));
          const batch: Record<string, SQLInputValue>[] = [];
          let batchBytes = 0;
          for (const row of iterator) {
            const size = Object.values(row).reduce<number>(
              (total, value) =>
                total +
                (typeof value === 'string'
                  ? Buffer.byteLength(value)
                  : ArrayBuffer.isView(value)
                    ? value.byteLength
                    : 8),
              0,
            );
            if (size > 16 * 1024 ** 2) throw Error('MIGRATION_ROW_TOO_LARGE');
            if (batch.length && batchBytes + size > 16 * 1024 ** 2) break;
            batch.push(row);
            batchBytes += size;
          }
          if (!batch.length) break;
          const values = batch.flatMap((row) => columns.map((column) => row[column.name]));
          const next = Number(batch.at(-1)!.__migration_rowid);
          await options.db.transaction(
            async () => {
              await options.db.query(
                `INSERT INTO ${qualified}(${columns.map((column) => identifier(column.name)).join(',')}) VALUES ${batch
                  .map(
                    (_, row) =>
                      `(${columns.map((_, column) => `$${row * columns.length + column + 1}`).join(',')})`,
                  )
                  .join(',')}`,
                values.map((value) =>
                  ArrayBuffer.isView(value)
                    ? Buffer.from(value.buffer, value.byteOffset, value.byteLength)
                    : value,
                ),
              );
              await options.db.query(
                `UPDATE ${schema}._import_state SET cursor=$2,rows=rows+$3 WHERE name=$1`,
                [table.name, next, batch.length],
              );
            },
            { lane: 'background' },
          );
          cursor = next;
          rows += batch.length;
          options.progress?.({ table: table.name, rows, completed: false });
        }
        if (identity) {
          const key = primary[0];
          await options.db.query(
            `SELECT setval(pg_get_serial_sequence($1,$2),coalesce((SELECT max(${key}) FROM ${qualified}),1),EXISTS(SELECT 1 FROM ${qualified}))`,
            [`${options.schema}.${table.name}`, columns.find((column) => column.pk)!.name],
          );
        }
        const [actual] = await options.db.query<{ count: number }>(
          `SELECT count(*) AS count FROM ${qualified}`,
        );
        const expected = (
          input.prepare(`SELECT count(*) AS count FROM ${name}`).get() as { count: number }
        ).count;
        if (actual.count !== expected || rows !== expected)
          throw Error('MIGRATION_ROW_COUNT_MISMATCH');
        await options.db.query(`UPDATE ${schema}._import_state SET completed=true WHERE name=$1`, [
          table.name,
        ]);
      }
      total += rows;
      options.progress?.({ table: table.name, rows, completed: true });
    }
    if ((await fileHashAsync(options.source)) !== sourceHash)
      throw Error('MIGRATION_SOURCE_CHANGED');
    return { tables: tables.length, rows: total, sourceHash };
  } finally {
    input.close();
  }
}
